// Refresh the pinned Node-compatible Mozilla CA bundle.
// Usage: dart run tool/refresh_mozilla_roots.dart --version YYYY-MM-DD --sha256 <sha256>
// The date and digest are intentionally explicit so bundle changes are reviewed.
import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';

import 'package:crypto/crypto.dart';

Future<void> main(List<String> args) async {
  final options = <String, String>{};
  for (var i = 0; i < args.length; i++) {
    final arg = args[i];
    if (!arg.startsWith('--') || i + 1 >= args.length) {
      stderr.writeln(
        'Usage: dart run tool/refresh_mozilla_roots.dart --version YYYY-MM-DD --sha256 <hex>',
      );
      exitCode = 64;
      return;
    }
    options[arg.substring(2)] = args[++i];
  }
  final version = options['version'];
  final expectedHash = options['sha256']?.toLowerCase();
  if (version == null ||
      expectedHash == null ||
      !RegExp(r'^\d{4}-\d{2}-\d{2}$').hasMatch(version) ||
      !RegExp(r'^[0-9a-f]{64}$').hasMatch(expectedHash)) {
    stderr.writeln(
      'Both --version YYYY-MM-DD and --sha256 <64 hex chars> are required.',
    );
    exitCode = 64;
    return;
  }

  final uri = Uri.parse('https://curl.se/ca/cacert-$version.pem');
  final request = await HttpClient().getUrl(uri);
  final response = await request.close();
  if (response.statusCode != HttpStatus.ok) {
    throw HttpException('Download $uri returned HTTP ${response.statusCode}');
  }
  final bytes = await response
      .fold<BytesBuilder>(
        BytesBuilder(copy: false),
        (builder, chunk) => builder..add(chunk),
      )
      .then((builder) => builder.takeBytes());
  final actualHash = sha256.convert(bytes).toString();
  if (actualHash != expectedHash) {
    throw StateError(
      'SHA-256 mismatch: expected $expectedHash, got $actualHash',
    );
  }
  final pem = utf8.decode(bytes);
  if (!pem.contains('Certificate data from Mozilla as of:')) {
    throw const FormatException(
      'Downloaded file does not identify Mozilla certificate data',
    );
  }
  final certs = RegExp(
    r'-----BEGIN CERTIFICATE-----[\s\S]*?-----END CERTIFICATE-----',
  ).allMatches(pem).map((match) => match.group(0)!).toList();
  if (certs.isEmpty) throw const FormatException('Bundle has no certificates');

  final vendor = File('vendor/certificates/mozilla-cacert-$version.pem');
  await vendor.parent.create(recursive: true);
  await vendor.writeAsBytes(bytes);
  final generated = StringBuffer()
    ..writeln('// Generated by tool/refresh_mozilla_roots.dart; do not edit.')
    ..writeln("const String mozillaRootBundleVersion = '$version';")
    ..writeln("const String mozillaRootBundleSha256 = '$actualHash';")
    ..writeln('const List<String> mozillaRootCertificates = <String>[');
  for (final cert in certs) {
    generated.writeln("  r'''$cert''',");
  }
  generated.writeln('];');
  await File(
    'lib/src/node/mozilla_roots.dart',
  ).writeAsString(generated.toString());
  stdout.writeln('Wrote ${certs.length} Mozilla roots ($version; $actualHash)');
}
